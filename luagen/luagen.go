/* Names {{{ */

var luaKeywords = map[string]bool{
	"and": true, "break": true, "do": true, "else": true, "elseif": true,
	"end": true, "false": true, "for": true, "function": true, "goto": true,
	"if": true, "in": true, "local": true, "nil": true, "not": true, "or": true,
	"repeat": true, "return": true, "then": true, "true": true, "until": true,
	"while": true,
}

func isName(s string) bool {
	if s == "" || luaKeywords[s] {
		return false
	}
	for i := 0; i < len(s); i++ {
		c := s[i]
		if !(c == '_' || 'a' <= c && c <= 'z' || 'A' <= c && c <= 'Z' || i > 0 && '0' <= c && c <= '9') {
			return false
		}
	}
	return true
}

// mangle returns a valid Lua identifier for a local name. Keywords get a
// trailing underscore (same as the reference Erde compiler) and other invalid
// names (ex. temporary names generated by the Erde parser, `(erde 1)`) are
// sanitized.
func mangle(name string) string {
	if isName(name) {
		return name
	}
	if luaKeywords[name] {
		return name + "_"
	}

	// Temporary names from the Erde parser
	if n := strings.TrimSuffix(strings.TrimPrefix(name, "(erde "), ")"); len(n) == len(name)-7 {
		return "__ERDE_TMP_" + n + "__"
	}

	var b strings.Builder
	b.WriteString("__ERDE_")
	for _, field := range strings.FieldsFunc(name, func(r rune) bool {
		return !(r == '_' || 'a' <= r && r <= 'z' || 'A' <= r && r <= 'Z' || '0' <= r && r <= '9')
	}) {
		b.WriteString(strings.ToUpper(field))
		b.WriteString("_")
	}
	b.WriteString("_")
	return b.String()
}

func (g *generator) pushScope() { g.scopes = append(g.scopes, map[string]bool{}) }

func (g *generator) popScope() { g.scopes = g.scopes[:len(g.scopes)-1] }

func (g *generator) declare(names ...string) {
	for _, name := range names {
		g.scopes[len(g.scopes)-1][name] = true
	}
}

func (g *generator) isLocal(name string) bool {
	for i := len(g.scopes) - 1; i >= 0; i-- {
		if g.scopes[i][name] {
			return true
		}
	}
	return false
}

// name writes a variable reference.
func (g *generator) name(name string) {
	if isName(name) || g.isLocal(name) || !luaKeywords[name] {
		g.write(mangle(name))
	} else {
		// A global w/ a keyword name (ex. Erde allows `end` as a name)
		g.write("_G[" + quote(name) + "]")
	}
}

func (g *generator) tmpName() string {
	g.tmpCounter++
	return "__ERDE_LOOP_" + strconv.Itoa(g.tmpCounter) + "__"
}

