/* Statements {{{ */

func (g *generator) block(stmts []ast.Stmt) {
	g.depth++
	g.pushScope()
	g.stmts(stmts)
	g.popScope()
	g.depth--
}

func (g *generator) stmts(stmts []ast.Stmt) {
	for i, stmt := range stmts {
		// Lua requires `break` / `return` to be the last statement in a block
		switch stmt.(type) {
		case *ast.BreakStmt, *ast.ReturnStmt:
			if i < len(stmts)-1 {
				g.sync(stmt.Line())
				g.keyword("do")
				g.stmt(stmt)
				g.keyword("end")
				continue
			}
		}

		g.stmt(stmt)
	}
}

func (g *generator) stmt(stmt ast.Stmt) {
	g.sync(stmt.Line())
	g.space()

	// Prevent ambiguous syntax (function call vs new statement) for statements
	// starting w/ a parenthesis, ex. `a = b` followed by `(f)()`.
	start := len(g.buf)
	defer func() {
		for start < len(g.buf) && (g.buf[start] == ' ' || g.buf[start] == '\n') {
			start++
		}
		if start < len(g.buf) && g.buf[start] == '(' {
			g.buf = append(g.buf[:start], append([]byte{';'}, g.buf[start:]...)...)
		}
	}()

	switch st := stmt.(type) {
	case *ast.AssignStmt:
		g.exprList(st.Lhs)
		g.write(" = ")
		g.exprList(st.Rhs)
	case *ast.LocalAssignStmt:
		g.localAssign(st)
	case *ast.FuncCallStmt:
		g.expr(st.Expr, 0)
	case *ast.DoBlockStmt:
		g.write("do")
		g.block(st.Stmts)
		g.end(st)
	case *ast.WhileStmt:
		g.write("while ")
		g.expr(st.Condition, 0)
		g.write(" do")
		g.block(st.Stmts)
		g.end(st)
	case *ast.RepeatStmt:
		g.write("repeat")
		// The condition can see locals declared in the loop body
		g.depth++
		g.pushScope()
		g.stmts(st.Stmts)
		g.depth--
		g.keyword("until ")
		g.expr(st.Condition, 0)
		g.popScope()
	case *ast.IfStmt:
		g.ifStmt(st)
	case *ast.NumberForStmt:
		g.numberFor(st)
	case *ast.GenericForStmt:
		g.genericFor(st)
	case *ast.FuncDefStmt:
		g.funcDef(st)
	case *ast.ReturnStmt:
		g.write("return")
		if len(st.Exprs) > 0 {
			g.write(" ")
			g.exprList(st.Exprs)
		}
	case *ast.BreakStmt:
		g.write("break")
	case *ast.LabelStmt:
		g.write("::" + mangle(st.Name) + "::")
	case *ast.GotoStmt:
		g.write("goto " + mangle(st.Label))
	default:
		panic(fmt.Sprintf("luagen: unknown statement %T", stmt))
	}
}

func (g *generator) localAssign(st *ast.LocalAssignStmt) {
	// The Lua parser produces this for `local function f()`, which (unlike
	// `local f = function()`) can refer to itself.
	if len(st.Names) == 1 && len(st.Exprs) == 1 {
		if fn, ok := st.Exprs[0].(*ast.FunctionExpr); ok {
			g.declare(st.Names[0])
			g.write("local function " + mangle(st.Names[0]))
			g.funcBody(fn, noSelf)
			return
		}
	}

	names := make([]string, len(st.Names))
	for i, name := range st.Names {
		names[i] = mangle(name)
	}

	g.write("local " + strings.Join(names, ", "))
	if len(st.Exprs) > 0 {
		g.write(" = ")
		g.exprList(st.Exprs)
	}

	g.declare(st.Names...)
}

func (g *generator) ifStmt(st *ast.IfStmt) {
	root := st
	g.write("if ")
	g.expr(st.Condition, 0)
	g.write(" then")
	g.block(st.Then)

	for {
		if len(st.Else) == 1 {
			if elseif, ok := st.Else[0].(*ast.IfStmt); ok {
				g.sync(elseif.Line())
				g.keyword("elseif ")
				g.expr(elseif.Condition, 0)
				g.write(" then")
				g.block(elseif.Then)
				st = elseif
				continue
			}
		}

		if len(st.Else) > 0 {
			g.keyword("else")
			g.block(st.Else)
		}

		g.end(root)
		return
	}
}

// loopVar returns the name to use for a loop variable in the loop header.
// Lua 5.5 loop variables are read-only, so if the body reassigns one we
// declare it under a temporary name and rebind it at the start of the body.
func (g *generator) loopVar(name string, body []ast.Stmt, rebinds *[]string) string {
	if !assignsName(body, name) {
		return mangle(name)
	}
	tmpName := g.tmpName()
	*rebinds = append(*rebinds, "local "+mangle(name)+" = "+tmpName)
	return tmpName
}

func (g *generator) loopBody(st ast.Stmt, names []string, rebinds []string, body []ast.Stmt) {
	g.write(" do")
	g.depth++
	g.pushScope()
	g.declare(names...)
	for _, rebind := range rebinds {
		g.write(" " + rebind)
	}
	g.stmts(body)
	g.popScope()
	g.depth--
	g.end(st)
}

func (g *generator) numberFor(st *ast.NumberForStmt) {
	var rebinds []string

	g.write("for " + g.loopVar(st.Name, st.Stmts, &rebinds) + " = ")
	g.expr(st.Init, 0)
	g.write(", ")
	g.expr(st.Limit, 0)
	if st.Step != nil {
		g.write(", ")
		g.expr(st.Step, 0)
	}

	g.loopBody(st, []string{st.Name}, rebinds, st.Stmts)
}

func (g *generator) genericFor(st *ast.GenericForStmt) {
	var rebinds []string

	names := make([]string, len(st.Names))
	for i, name := range st.Names {
		names[i] = g.loopVar(name, st.Stmts, &rebinds)
	}

	g.write("for " + strings.Join(names, ", ") + " in ")
	g.exprList(st.Exprs)

	g.loopBody(st, st.Names, rebinds, st.Stmts)
}

// funcPath returns `a.b.c` for a function declaration name, or false if the
// name cannot be written as a function declaration name.
func (g *generator) funcPath(expr ast.Expr) (string, bool) {
	switch ex := expr.(type) {
	case *ast.IdentExpr:
		if isName(ex.Value) || g.isLocal(ex.Value) {
			return mangle(ex.Value), true
		}
	case *ast.AttrGetExpr:
		key, ok := ex.Key.(*ast.StringExpr)
		if !ok || !isName(key.Value) {
			return "", false
		}
		if path, ok := g.funcPath(ex.Object); ok {
			return path + "." + key.Value, true
		}
	}
	return "", false
}

func (g *generator) funcDef(st *ast.FuncDefStmt) {
	if st.Name.Func != nil {
		if path, ok := g.funcPath(st.Name.Func); ok {
			g.write("function " + path)
			g.funcBody(st.Func, noSelf)
		} else {
			g.expr(st.Name.Func, 0)
			g.write(" = function")
			g.funcBody(st.Func, noSelf)
		}
		return
	}

	if path, ok := g.funcPath(st.Name.Receiver); ok && isName(st.Name.Method) {
		g.write("function " + path + ":" + st.Name.Method)
		g.funcBody(st.Func, implicitSelf)
		return
	}

	g.prefixExpr(st.Name.Receiver)
	g.index(&ast.StringExpr{Value: st.Name.Method})
	g.write(" = function")
	g.funcBody(st.Func, explicitSelf)
}

