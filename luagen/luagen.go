/* Expressions {{{ */

// Lua operator precedences (higher binds tighter)
const (
	precOr = iota + 1
	precAnd
	precCompare
	precConcat
	precAdd
	precMul
	precUnary
	precPow
)

var arithmeticPrecs = map[string]int{
	"+": precAdd, "-": precAdd, "*": precMul, "/": precMul, "%": precMul, "^": precPow,
}

func (g *generator) exprList(exprs []ast.Expr) {
	for i, expr := range exprs {
		if i > 0 {
			g.write(", ")
		}
		g.expr(expr, 0)
	}
}

// binop writes `lhs op rhs`, parenthesized if its precedence is lower than
// `minPrec`.
func (g *generator) binop(op string, prec int, rightAssoc bool, lhs, rhs ast.Expr, minPrec int) {
	if prec < minPrec {
		g.write("(")
		defer g.write(")")
	}

	lhsPrec, rhsPrec := prec, prec+1
	if rightAssoc {
		lhsPrec, rhsPrec = prec+1, prec
	}

	g.expr(lhs, lhsPrec)
	g.write(" " + op + " ")
	g.expr(rhs, rhsPrec)
}

func (g *generator) unop(op string, operand ast.Expr, minPrec int) {
	if precUnary < minPrec {
		g.write("(")
		defer g.write(")")
	}

	g.write(op)
	if _, ok := operand.(*ast.UnaryMinusOpExpr); ok && op == "-" {
		g.write(" ") // `--` would be a comment
	}
	g.expr(operand, precUnary)
}

func (g *generator) expr(expr ast.Expr, minPrec int) {
	g.sync(expr.Line())

	switch ex := expr.(type) {
	case *ast.NilExpr:
		g.write("nil")
	case *ast.TrueExpr:
		g.write("true")
	case *ast.FalseExpr:
		g.write("false")
	case *ast.NumberExpr:
		g.number(ex.Value)
	case *ast.StringExpr:
		g.write(quote(ex.Value))
	case *ast.Comma3Expr:
		if ex.AdjustRet {
			g.write("(...)")
		} else {
			g.write("...")
		}
	case *ast.IdentExpr:
		g.name(ex.Value)
	case *ast.AttrGetExpr:
		g.prefixExpr(ex.Object)
		g.index(ex.Key)
	case *ast.TableExpr:
		g.table(ex)
	case *ast.FuncCallExpr:
		if ex.AdjustRet {
			g.write("(")
			defer g.write(")")
		}
		g.call(ex)
	case *ast.LogicalOpExpr:
		if ex.Operator == "or" {
			g.binop("or", precOr, false, ex.Lhs, ex.Rhs, minPrec)
		} else {
			g.binop("and", precAnd, false, ex.Lhs, ex.Rhs, minPrec)
		}
	case *ast.RelationalOpExpr:
		g.binop(ex.Operator, precCompare, false, ex.Lhs, ex.Rhs, minPrec)
	case *ast.StringConcatOpExpr:
		g.binop("..", precConcat, true, ex.Lhs, ex.Rhs, minPrec)
	case *ast.ArithmeticOpExpr:
		prec := arithmeticPrecs[ex.Operator]
		g.binop(ex.Operator, prec, prec == precPow, ex.Lhs, ex.Rhs, minPrec)
	case *ast.UnaryMinusOpExpr:
		g.unop("-", ex.Expr, minPrec)
	case *ast.UnaryNotOpExpr:
		g.unop("not ", ex.Expr, minPrec)
	case *ast.UnaryLenOpExpr:
		g.unop("#", ex.Expr, minPrec)
	case *ast.FunctionExpr:
		g.write("function")
		g.funcBody(ex, noSelf)
	default:
		panic(fmt.Sprintf("luagen: unknown expression %T", expr))
	}
}

// prefixExpr writes an expression that is indexed or called, which Lua only
// allows for names, index / call expressions, or parenthesized expressions.
func (g *generator) prefixExpr(expr ast.Expr) {
	switch expr.(type) {
	case *ast.IdentExpr, *ast.AttrGetExpr, *ast.FuncCallExpr:
		g.expr(expr, 0)
	default:
		g.write("(")
		g.expr(expr, 0)
		g.write(")")
	}
}

func (g *generator) index(key ast.Expr) {
	if str, ok := key.(*ast.StringExpr); ok && isName(str.Value) {
		g.write("." + str.Value)
		return
	}
	g.write("[")
	g.expr(key, 0)
	g.write("]")
}

func (g *generator) call(ex *ast.FuncCallExpr) {
	if ex.Func != nil {
		g.prefixExpr(ex.Func)
		g.args(ex.Args)
		return
	}

	if isName(ex.Method) {
		g.prefixExpr(ex.Receiver)
		g.write(":" + ex.Method)
		g.args(ex.Args)
		return
	}

	// Methods that are Lua keywords (ex. `a:end()`) can't use `:`, so we need
	// to pass `self` manually.
	if ident, ok := ex.Receiver.(*ast.IdentExpr); ok {
		g.prefixExpr(ident)
		g.index(&ast.StringExpr{Value: ex.Method})
		g.args(append([]ast.Expr{ident}, ex.Args...))
		return
	}

	// Avoid evaluating the receiver twice
	g.write("(function(self, ...) return self[" + quote(ex.Method) + "](self, ...) end)")
	g.args(append([]ast.Expr{ex.Receiver}, ex.Args...))
}

func (g *generator) args(args []ast.Expr) {
	g.write("(")
	g.exprList(args)
	g.write(")")
}

func (g *generator) table(ex *ast.TableExpr) {
	g.write("{")
	for i, field := range ex.Fields {
		if i > 0 {
			g.write(", ")
		}

		if field.Key != nil {
			if str, ok := field.Key.(*ast.StringExpr); ok && isName(str.Value) {
				g.write(str.Value)
			} else {
				g.write("[")
				g.expr(field.Key, 0)
				g.write("]")
			}
			g.write(" = ")
		}

		g.expr(field.Value, 0)
	}
	g.write("}")
}

const (
	noSelf       = iota
	implicitSelf // `function a:b()`
	explicitSelf // `a.b = function(self)`
)

// funcBody writes `(params) body end`.
func (g *generator) funcBody(fn *ast.FunctionExpr, self int) {
	g.depth++
	g.pushScope()

	params := make([]string, 0, len(fn.ParList.Names)+2)
	switch self {
	case implicitSelf:
		g.declare("self")
	case explicitSelf:
		g.declare("self")
		params = append(params, "self")
	}
	for _, name := range fn.ParList.Names {
		params = append(params, mangle(name))
	}
	if fn.ParList.HasVargs {
		params = append(params, "...")
	}
	g.declare(fn.ParList.Names...)

	g.write("(" + strings.Join(params, ", ") + ")")
	g.stmts(fn.Stmts)

	g.popScope()
	g.depth--

	g.sync(fn.LastLine())
	g.keyword("end")
}

func (g *generator) number(value string) {
	n, err := strconv.ParseFloat(value, 64)
	switch {
	case err == nil && n > 1e308:
		g.write("1e999") // inf
	case err != nil && strings.Contains(strings.ToLower(value), "nan"):
		g.write("(0/0)")
	default:
		g.write(value)
	}
}

// quote returns a Lua string literal, valid in all Lua versions.
func quote(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for i := 0; i < len(s); i++ {
		switch c := s[i]; c {
		case '"':
			b.WriteString(`\"`)
		case '\\':
			b.WriteString(`\\`)
		case '\n':
			b.WriteString(`\n`)
		case '\r':
			b.WriteString(`\r`)
		case '\t':
			b.WriteString(`\t`)
		default:
			if c < 32 || c == 127 {
				fmt.Fprintf(&b, "\\%03d", c)
			} else {
				b.WriteByte(c)
			}
		}
	}
	b.WriteByte('"')
	return b.String()
}

