// Package luagen generates Lua source code from a chunk (ex. from
// `parse.Parse` or `parse.ParseErde`).
//
// The generated code targets Lua 5.1+ and LuaJIT, except that `goto` (also
// used by Erde's `continue`) requires Lua 5.2+ or LuaJIT, and Erde bit
// operators require a `bit32` library (builtin in Lua 5.2, otherwise a
// polyfill).
//
// Statements are placed on the same line as in the original source (where
// possible), so that line numbers in Lua errors match the original source.
package luagen

import (
	"fmt"
	"strconv"
	"strings"

	"github.com/taybart/go-erde/ast"
)

// Generate returns Lua source code for a chunk.
func Generate(chunk []ast.Stmt) string {
	g := &generator{line: 1, fresh: true, scopes: []map[string]bool{{}}}
	g.stmts(chunk)
	g.write("\n")
	return string(g.buf)
}

type generator struct {
	buf []byte

	// Current output line
	line int
	// Block depth, for indentation
	depth int
	// Whether we are at the start of a line (nothing written yet)
	fresh bool

	// Declared local names, used to resolve names that are not valid Lua
	// identifiers (see `name`).
	scopes []map[string]bool

	tmpCounter int
}

/* Output helpers {{{ */

func (g *generator) write(s string) {
	g.buf = append(g.buf, s...)
	g.fresh = false
}

// sync moves the output to `line` (never backwards), to keep line numbers in
// the generated code consistent w/ the original source.
func (g *generator) sync(line int) {
	if line <= g.line {
		return
	}
	for ; g.line < line; g.line++ {
		g.buf = append(g.buf, '\n')
	}
	g.buf = append(g.buf, strings.Repeat("  ", g.depth)...)
	g.fresh = true
}

// space separates tokens, unless we are at the start of a line.
func (g *generator) space() {
	if !g.fresh {
		g.write(" ")
	}
}

// end closes a block statement, on the line of its closing token.
func (g *generator) end(stmt ast.Stmt) {
	g.sync(stmt.LastLine())
	g.keyword("end")
}

// keyword writes a keyword, separated from the previous token.
func (g *generator) keyword(keyword string) {
	g.space()
	g.write(keyword)
}

