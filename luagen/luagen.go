/* Analysis {{{ */

// assignsName reports whether statements (including nested functions) assign
// to `name`. Shadowing is ignored, so this may report false positives.
func assignsName(stmts []ast.Stmt, name string) bool {
	found := false

	isName := func(expr ast.Expr) bool {
		ident, ok := expr.(*ast.IdentExpr)
		return ok && ident.Value == name
	}

	var visitStmts func([]ast.Stmt)
	var visitExpr func(ast.Expr)

	visitExprs := func(exprs []ast.Expr) {
		for _, expr := range exprs {
			visitExpr(expr)
		}
	}

	visitExpr = func(expr ast.Expr) {
		switch ex := expr.(type) {
		case *ast.AttrGetExpr:
			visitExpr(ex.Object)
			visitExpr(ex.Key)
		case *ast.TableExpr:
			for _, field := range ex.Fields {
				if field.Key != nil {
					visitExpr(field.Key)
				}
				visitExpr(field.Value)
			}
		case *ast.FuncCallExpr:
			if ex.Func != nil {
				visitExpr(ex.Func)
			}
			if ex.Receiver != nil {
				visitExpr(ex.Receiver)
			}
			visitExprs(ex.Args)
		case *ast.LogicalOpExpr:
			visitExpr(ex.Lhs)
			visitExpr(ex.Rhs)
		case *ast.RelationalOpExpr:
			visitExpr(ex.Lhs)
			visitExpr(ex.Rhs)
		case *ast.StringConcatOpExpr:
			visitExpr(ex.Lhs)
			visitExpr(ex.Rhs)
		case *ast.ArithmeticOpExpr:
			visitExpr(ex.Lhs)
			visitExpr(ex.Rhs)
		case *ast.UnaryMinusOpExpr:
			visitExpr(ex.Expr)
		case *ast.UnaryNotOpExpr:
			visitExpr(ex.Expr)
		case *ast.UnaryLenOpExpr:
			visitExpr(ex.Expr)
		case *ast.FunctionExpr:
			visitStmts(ex.Stmts)
		}
	}

	visitStmts = func(stmts []ast.Stmt) {
		for _, stmt := range stmts {
			switch st := stmt.(type) {
			case *ast.AssignStmt:
				for _, lhs := range st.Lhs {
					found = found || isName(lhs)
				}
				visitExprs(st.Lhs)
				visitExprs(st.Rhs)
			case *ast.LocalAssignStmt:
				visitExprs(st.Exprs)
			case *ast.FuncCallStmt:
				visitExpr(st.Expr)
			case *ast.DoBlockStmt:
				visitStmts(st.Stmts)
			case *ast.WhileStmt:
				visitExpr(st.Condition)
				visitStmts(st.Stmts)
			case *ast.RepeatStmt:
				visitStmts(st.Stmts)
				visitExpr(st.Condition)
			case *ast.IfStmt:
				visitExpr(st.Condition)
				visitStmts(st.Then)
				visitStmts(st.Else)
			case *ast.NumberForStmt:
				visitExpr(st.Init)
				visitExpr(st.Limit)
				if st.Step != nil {
					visitExpr(st.Step)
				}
				visitStmts(st.Stmts)
			case *ast.GenericForStmt:
				visitExprs(st.Exprs)
				visitStmts(st.Stmts)
			case *ast.FuncDefStmt:
				if st.Name.Func != nil {
					found = found || isName(st.Name.Func)
					visitExpr(st.Name.Func)
				} else {
					visitExpr(st.Name.Receiver)
				}
				visitExpr(st.Func)
			case *ast.ReturnStmt:
				visitExprs(st.Exprs)
			}
		}
	}

	visitStmts(stmts)
	return found
}

